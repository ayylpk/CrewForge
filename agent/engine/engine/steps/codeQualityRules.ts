// ============================================================
// codeQualityRules.ts —— 实现器代码质量纪律（借鉴行业标杆的系统提示词姿态）
//
//   为什么单独成模块：这条纪律此前散落在各处、且**没有任何一条被断言覆盖**——
//   于是它随时可能像那四条组件库规约一样变成"没人引用的死文本"。
//   这里单一来源 + 冒烟断言"两个实现器都真的注入了它"。
//
//   取向（都是**可执行的反过度设计**，不是空话）：
//     最小改动 / 匹配现有风格 / 优先复用 / 不新增依赖 / 不留占位实现 / 契约逐字照抄
// ============================================================

export const CODE_QUALITY_RULES = `
## 代码质量纪律（强制，与上文冲突时以本节为准）
1. **只写被要求的东西**：不新增任务没要求的功能、不加"将来可能用到"的抽象层、不加配置开关或可选参数。
2. **最小改动**：修改已有文件时只动必须动的地方，保持其余行原样；不要顺手重构、重排版或改名。
3. **匹配现有风格**：命名、错误处理、日志、注释语言与同目录既有文件一致（语言/大小写/命名法都照抄）。
4. **先复用再造轮子**：写新函数前先看项目里是否已有等价工具/常量/组件；有就 import，不要复制一份。
5. **不新增依赖**：除技术基线与 package.json/pom.xml 已声明的以外，不引入任何新依赖。
6. **不吞错误**：不使用空的 catch、不用打印代替抛出、不把异常转成"静默返回 null"；错误按同项目既有方式处理。
7. **注释只写"为什么"**：不写复述代码本身的注释，不写大段分隔装饰。
8. **不留占位实现**：不写 TODO/FIXME/throw new Error("not implemented")/返回假数据当实现——这类代码能编译但行为是错的。
9. **契约逐字照抄**：接口 method/path、字段名、枚举值、响应包装（code/msg/data）一律照抄任务描述与契约，不改名、不翻译、不自创。
10. **完成即完整**：一个文件要么是可运行的完整实现，要么不产出——不接受"部分实现 + 注释说明后续补充"。
`.trim();

export const CODE_QUALITY_RULES_COUNT = 10;
